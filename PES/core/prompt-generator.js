/**
 * PES Phase 2: Prompt Variant Generator
 * 
 * Generates intelligent prompt variations using LLM based on
 * insights from debate analysis
 */

import { generateWithLLM } from '../services/llmService.js';

/**
 * Generate prompt variants based on baseline and insights
 * @param {string} baselinePrompt - Current baseline prompt
 * @param {Object} insights - Aggregated insights from debate analysis
 * @param {number} count - Number of variants to generate (default: 5)
 * @returns {Promise<Array>} Array of prompt variants
 */
export async function generatePromptVariants(baselinePrompt, insights, count = 5) {
  console.log(`[Prompt Generator] Generating ${count} prompt variants...`);
  
  if (!baselinePrompt || !insights) {
    throw new Error('Baseline prompt and insights are required');
  }
  
  // Build generation prompt for LLM
  const generationPrompt = buildGenerationPrompt(baselinePrompt, insights, count);
  
  try {
    const response = await generateWithLLM(generationPrompt, {
      model: 'gpt-4-turbo-preview',
      temperature: 0.7,
      max_tokens: 4000,
      response_format: { type: 'json_object' }
    });
    
    const parsed = JSON.parse(response);
    const rawVariants = parsed.variants || [];
    
    if (!Array.isArray(rawVariants) || rawVariants.length === 0) {
      throw new Error('No variants generated by LLM');
    }
    
    // Process and validate variants
    const variants = rawVariants.map((v, i) => {
      const version = generateVersionNumber(i);
      
      return {
        version: version,
        prompt_text: v.prompt_text || v.prompt || baselinePrompt,
        hypothesis: v.hypothesis || 'No hypothesis provided',
        expected_improvement: v.expected_improvement || 'Unknown',
        changes_summary: v.changes_summary || generateDiffSummary(baselinePrompt, v.prompt_text),
        strategic_focus: v.strategic_focus || [],
        metadata: {
          generated_at: new Date().toISOString(),
          based_on_insights: insights.debates_analyzed,
          generation_temperature: 0.7
        }
      };
    });
    
    console.log(`[Prompt Generator] Successfully generated ${variants.length} variants`);
    
    return variants;
  } catch (error) {
    console.error('[Prompt Generator] Error generating variants:', error.message);
    
    // Fallback: generate basic variants with simple modifications
    console.log('[Prompt Generator] Falling back to rule-based generation...');
    return generateFallbackVariants(baselinePrompt, insights, count);
  }
}

/**
 * Build the generation prompt for LLM
 * @param {string} baselinePrompt - Current baseline prompt
 * @param {Object} insights - Aggregated insights
 * @param {number} count - Number of variants
 * @returns {string} Generation prompt
 */
function buildGenerationPrompt(baselinePrompt, insights, count) {
  return `You are an expert prompt engineer optimizing the ONESEEK AI debate prompt based on performance data.

CURRENT BASELINE PROMPT:
${baselinePrompt}

PERFORMANCE INSIGHTS FROM ${insights.debates_analyzed} DEBATES:

Overall Performance:
- Average votes per debate: ${insights.overall_metrics?.avg_votes_per_debate?.toFixed(1) || 'N/A'}
- Win rate: ${((insights.overall_metrics?.win_rate || 0) * 100).toFixed(1)}%
- Average mentions: ${insights.overall_metrics?.avg_mentions?.toFixed(1) || 'N/A'}

Successful Patterns (what worked well):
${insights.successful_patterns?.slice(0, 8).map((p, i) => `${i + 1}. ${p}`).join('\n') || 'None identified'}

Weaknesses (areas for improvement):
${insights.weaknesses?.slice(0, 6).map((w, i) => `${i + 1}. ${w}`).join('\n') || 'None identified'}

Winning Styles (approaches that got votes):
${insights.winning_styles?.slice(0, 6).map((s, i) => `${i + 1}. ${s}`).join('\n') || 'None identified'}

Strategic Recommendations:
${insights.strategic_recommendations?.slice(0, 6).map((r, i) => `${i + 1}. ${r}`).join('\n') || 'None identified'}

YOUR TASK:
Generate ${count} distinct prompt variations that:
1. Apply insights from successful patterns
2. Address identified weaknesses
3. Test different synthesis approaches
4. Emphasize vote-winning characteristics
5. Maintain ONESEEK's core identity (objective, balanced, synthesizing AI)
6. Keep changes focused and measurable

REQUIREMENTS:
- Each variant should test a specific hypothesis
- Include {context} placeholders for dynamic data injection
- Maintain professional tone and structure
- Vary approaches across variants (don't just tweak wording)
- Keep prompts between 200-800 words

OUTPUT FORMAT (JSON):
{
  "variants": [
    {
      "prompt_text": "Complete prompt text with {context} placeholders...",
      "hypothesis": "Clear statement of what this variant tests (e.g., 'Emphasizing data-driven synthesis increases vote count')",
      "expected_improvement": "Predicted impact on metrics (e.g., '+20% votes, +15% mentions')",
      "changes_summary": "Brief description of key changes from baseline",
      "strategic_focus": ["focus area 1", "focus area 2"]
    },
    ...
  ]
}`;
}

/**
 * Generate fallback variants using rule-based modifications
 * @param {string} baselinePrompt - Baseline prompt
 * @param {Object} insights - Insights object
 * @param {number} count - Number of variants
 * @returns {Array} Fallback variants
 */
function generateFallbackVariants(baselinePrompt, insights, count) {
  const variants = [];
  
  const modifications = [
    {
      name: 'data-emphasis',
      hypothesis: 'Emphasizing data and evidence increases credibility',
      modify: (prompt) => prompt + '\n\nAlways prioritize data-driven analysis and cite evidence when available.',
      focus: ['data', 'evidence']
    },
    {
      name: 'synthesis-focus',
      hypothesis: 'Stronger synthesis approach improves vote count',
      modify: (prompt) => prompt.replace('synthesize', 'deeply synthesize and integrate').replace('analyze', 'thoroughly analyze and compare'),
      focus: ['synthesis', 'integration']
    },
    {
      name: 'clarity-enhancement',
      hypothesis: 'Clearer structure and simpler language improves accessibility',
      modify: (prompt) => prompt + '\n\nUse clear structure with bullet points. Avoid jargon. Be concise.',
      focus: ['clarity', 'structure']
    },
    {
      name: 'meta-awareness',
      hypothesis: 'Acknowledging different perspectives explicitly shows depth',
      modify: (prompt) => prompt + '\n\nExplicitly acknowledge and weigh different viewpoints from other AIs.',
      focus: ['meta-analysis', 'perspective']
    },
    {
      name: 'balanced-approach',
      hypothesis: 'Neutral tone with pros/cons increases trust',
      modify: (prompt) => prompt + '\n\nPresent balanced analysis with both advantages and limitations.',
      focus: ['balance', 'neutrality']
    }
  ];
  
  for (let i = 0; i < Math.min(count, modifications.length); i++) {
    const mod = modifications[i];
    const version = generateVersionNumber(i);
    
    variants.push({
      version: version,
      prompt_text: mod.modify(baselinePrompt),
      hypothesis: mod.hypothesis,
      expected_improvement: 'Unknown (fallback generation)',
      changes_summary: `Applied ${mod.name} modification`,
      strategic_focus: mod.focus,
      metadata: {
        generated_at: new Date().toISOString(),
        generation_method: 'fallback',
        based_on_insights: insights.debates_analyzed
      }
    });
  }
  
  return variants;
}

/**
 * Generate version number for variant
 * @param {number} index - Variant index
 * @returns {string} Version string (e.g., "v1.1.0-a")
 */
function generateVersionNumber(index) {
  const currentDate = new Date();
  const minor = currentDate.getMonth() + 1; // 1-12
  const patch = currentDate.getDate(); // 1-31
  const letter = String.fromCharCode(97 + index); // a, b, c, ...
  
  return `v1.${minor}.${patch}-${letter}`;
}

/**
 * Generate a summary of differences between prompts
 * @param {string} baseline - Baseline prompt
 * @param {string} variant - Variant prompt
 * @returns {string} Diff summary
 */
function generateDiffSummary(baseline, variant) {
  if (!baseline || !variant) {
    return 'Unable to compare';
  }
  
  const baselineWords = baseline.split(/\s+/).length;
  const variantWords = variant.split(/\s+/).length;
  const wordDiff = variantWords - baselineWords;
  
  let summary = `Length: ${wordDiff > 0 ? '+' : ''}${wordDiff} words`;
  
  // Check for major additions
  if (variant.length > baseline.length * 1.2) {
    summary += ', significant additions';
  } else if (variant.length < baseline.length * 0.8) {
    summary += ', significant reductions';
  } else {
    summary += ', similar length';
  }
  
  return summary;
}

/**
 * Validate a prompt variant
 * @param {Object} variant - Prompt variant to validate
 * @returns {Object} Validation result
 */
export function validatePromptVariant(variant) {
  const errors = [];
  const warnings = [];
  
  if (!variant.prompt_text || variant.prompt_text.length < 50) {
    errors.push('Prompt text too short (minimum 50 characters)');
  }
  
  if (variant.prompt_text && variant.prompt_text.length > 5000) {
    warnings.push('Prompt text very long (>5000 characters), may affect performance');
  }
  
  if (!variant.hypothesis) {
    warnings.push('No hypothesis provided');
  }
  
  if (!variant.version) {
    errors.push('Version number missing');
  }
  
  // Check for template placeholders
  if (variant.prompt_text && !variant.prompt_text.includes('{')) {
    warnings.push('No template placeholders found, prompt may not be dynamic');
  }
  
  return {
    valid: errors.length === 0,
    errors,
    warnings
  };
}

export default {
  generatePromptVariants,
  validatePromptVariant,
  generateVersionNumber
};
