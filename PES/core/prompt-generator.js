/**
 * PES Phase 2: Prompt Variant Generator
 * 
 * Generates intelligent prompt variations using ONESEEK based on
 * insights from debate analysis
 */

import { generateWithOneseek } from '../services/oneseekService.js';
// PHASE 3: Category-aware prompt generation
import { getCategorySpecificGuidance } from './debate-classifier.js';

/**
 * Generate prompt variants based on baseline and insights
 * @param {string} baselinePrompt - Current baseline prompt
 * @param {Object} insights - Aggregated insights from debate analysis
 * @param {number} count - Number of variants to generate (default: 5)
 * @param {Array} categoryDistribution - PHASE 3: Category distribution for category-aware generation
 * @returns {Promise<Array>} Array of prompt variants
 */
export async function generatePromptVariants(baselinePrompt, insights, count = 5, categoryDistribution = null) {
  console.log(`[Prompt Generator] Generating ${count} prompt variants...`);
  
  if (!baselinePrompt || !insights) {
    throw new Error('Baseline prompt and insights are required');
  }
  
  // Build generation prompt for LLM
  const generationPrompt = buildGenerationPrompt(baselinePrompt, insights, count, categoryDistribution);
  
  try {
    // Use ONESEEK to generate variants based on insights
    const response = await generateWithOneseek(generationPrompt, {
      temperature: 0.7,
      max_tokens: 4000
    });
    
    // Parse JSON from ONESEEK response
    let parsed;
    try {
      const jsonMatch = response.response.match(/\{[\s\S]*\}/);
      if (jsonMatch) {
        parsed = JSON.parse(jsonMatch[0]);
      } else {
        throw new Error('No JSON found in response');
      }
    } catch (parseError) {
      console.warn('[Prompt Generator] Could not parse JSON, using rule-based generation');
      return generateFallbackVariants(baselinePrompt, insights, count);
    }
    const rawVariants = parsed.variants || [];
    
    if (!Array.isArray(rawVariants) || rawVariants.length === 0) {
      throw new Error('No variants generated by LLM');
    }
    
    // Process and validate variants
    const variants = rawVariants.map((v, i) => {
      const version = generateVersionNumber(i);
      
      return {
        version: version,
        prompt_text: v.prompt_text || v.prompt || baselinePrompt,
        hypothesis: v.hypothesis || 'No hypothesis provided',
        expected_improvement: v.expected_improvement || 'Unknown',
        changes_summary: v.changes_summary || generateDiffSummary(baselinePrompt, v.prompt_text),
        strategic_focus: v.strategic_focus || [],
        metadata: {
          generated_at: new Date().toISOString(),
          based_on_insights: insights.debates_analyzed,
          generation_temperature: 0.7
        }
      };
    });
    
    console.log(`[Prompt Generator] Successfully generated ${variants.length} variants`);
    
    return variants;
  } catch (error) {
    console.error('[Prompt Generator] Error generating variants:', error.message);
    
    // Fallback: generate basic variants with simple modifications
    console.log('[Prompt Generator] Falling back to rule-based generation...');
    return generateFallbackVariants(baselinePrompt, insights, count);
  }
}

/**
 * Build the generation prompt for LLM
 * @param {string} baselinePrompt - Current baseline prompt
 * @param {Object} insights - Aggregated insights
 * @param {number} count - Number of variants
 * @param {Array} categoryDistribution - PHASE 3: Category distribution
 * @returns {string} Generation prompt
 */
function buildGenerationPrompt(baselinePrompt, insights, count, categoryDistribution = null) {
  // PHASE 3: Category-aware prompt generation
  let categorySection = '';
  if (categoryDistribution && categoryDistribution.length > 0) {
    const dominantCategory = categoryDistribution[0];
    const categoryGuidance = getCategorySpecificGuidance(dominantCategory.main);
    
    categorySection = `
KATEGORI-DISTRIBUTION I DENNA EVOLUTION:
${categoryDistribution.slice(0, 3).map(c => `- ${c.main}/${c.sub}: ${c.count} debatter (${c.percentage}%)`).join('\n')}

DOMINERANDE KATEGORI: ${dominantCategory.main}/${dominantCategory.sub}
KATEGORI-SPECIFIK VÄGLEDNING FÖR ${dominantCategory.main}:
${categoryGuidance}
`;
  }

  return `Du är en expert på prompt engineering som optimerar ONESEEK AI:s debatt-prompt baserat på prestandadata.

NUVARANDE BASELINE PROMPT:
${baselinePrompt}

PRESTANDAINSIKTER FRÅN ${insights.debates_analyzed} DEBATTER:

Övergripande Prestanda:
- Genomsnittliga röster per debatt: ${insights.overall_metrics?.avg_votes_per_debate?.toFixed(1) || 'N/A'}
- Vinstfrekvens: ${((insights.overall_metrics?.win_rate || 0) * 100).toFixed(1)}%
- Genomsnittliga omnämnanden: ${insights.overall_metrics?.avg_mentions?.toFixed(1) || 'N/A'}
${categorySection}
Framgångsrika Mönster (vad som fungerade bra):
${insights.successful_patterns?.slice(0, 8).map((p, i) => `${i + 1}. ${p}`).join('\n') || 'Inga identifierade'}

Svagheter (områden för förbättring):
${insights.weaknesses?.slice(0, 6).map((w, i) => `${i + 1}. ${w}`).join('\n') || 'Inga identifierade'}

Vinnande Stilar (metoder som fick röster):
${insights.winning_styles?.slice(0, 6).map((s, i) => `${i + 1}. ${s}`).join('\n') || 'Inga identifierade'}

Strategiska Rekommendationer:
${insights.strategic_recommendations?.slice(0, 6).map((r, i) => `${i + 1}. ${r}`).join('\n') || 'Inga identifierade'}

DIN UPPGIFT:
Generera ${count} distinkta promptvariationer som:
1. **UTGÅR ALLTID FRÅN BASELINE-PROMTEN OVAN** - bevara grundstrukturen
2. Tillämpar insikter från framgångsrika mönster
3. Adresserar identifierade svagheter
4. Testar olika syntesmetoder
5. Behåller ONESEEK:s kärnidentitet (objektiv, balanserad, syntetiserande AI)
6. Håller förändringar fokuserade och mätbara
${categoryDistribution && categoryDistribution.length > 0 ? `7. ANPASSAR STIL TILL DOMINERANDE KATEGORI (${categoryDistribution[0].main}) enligt kategori-specifik vägledning ovan` : ''}

KRITISKT VIKTIGA KRAV:
- **UTGÅ ALLTID FRÅN BASELINE-PROMPTEN** - använd den som bas, modifiera endast specifika delar
- **GÖR INKREMENTELLA ÄNDRINGAR** - lägg till, ta bort eller ändra formuleringen, inte hela strukturen
- **BEHÅLL GRUNDSTRUKTUREN** - om baseline har rubriker, punktlistor eller stycken, behåll den strukturen
- **SKRIV ALDRIG OM HELA PROMPTEN** - varje variant ska vara baseline + specifika ändringar
- Varje variant ska testa EN specifik hypotes genom en riktad ändring
- Inkludera {context} platshållare för dynamisk data-injektion
- Behåll professionell ton och struktur
- Håll prompter mellan 200-800 ord
- **ALLA PROMPTER MÅSTE VARA 100% PÅ SVENSKA**
- **VARJE VARIANT MÅSTE VARA FULLSTÄNDIGT PÅ SVENSKA**

EXEMPEL PÅ BRA ÄNDRINGAR (från baseline):
✓ Lägga till ett stycke om datadriven analys
✓ Ändra formulering i ett specifikt avsnitt för att betona syntes
✓ Ta bort/ersätta en mening som inte fungerade bra
✓ Lägga till en instruktion om struktur
✗ INTE: Skapa en helt ny prompt från grunden
✗ INTE: Ändra hela tonen eller strukturen radikalt

UTGÅNGSFORMAT (JSON):
Returnera JSON med följande struktur. VARJE variant måste innehålla DEN FAKTISKA, FULLSTÄNDIGA PROMPTEN i prompt_text fältet - inte beskrivningar eller placeholders.

{
  "variants": [
    {
      "prompt_text": "[HELA BASELINE-PROMPTEN MED DINA SPECIFIKA ÄNDRINGAR APPLICERADE - skriv ut hela den modifierade prompten här, INTE en beskrivning]",
      "hypothesis": "Betona datadriven syntes ökar röstantal",
      "expected_improvement": "+20% röster, +15% omnämnanden",
      "changes_summary": "Lagt till stycke om datadrivet tänkande efter första meningen. Ändrat formulering i stycke 2 från 'syntetisera' till 'djupt integrera och analysera'. Lagt till bullet-punkt om konkreta exempel.",
      "strategic_focus": ["data-driven analys", "syntes"]
    }
  ]
}

KRITISKT VIKTIGT FÖR prompt_text:
- prompt_text ska innehålla den FAKTISKA, FULLSTÄNDIGA prompten (inte "BASELINE-PROMPTEN MED..." eller andra beskrivningar)
- Kopiera hela baseline-prompten och applicera dina ändringar direkt i texten
- Om baseline är 50 rader, ska prompt_text också vara ~50 rader med dina ändringar
- Behåll alla {context} platshållare från baseline
- SKRIV ALDRIG "BASELINE-PROMPTEN MED ÄNDRINGAR" - skriv den faktiska prompten!

EXEMPEL PÅ RÄTT (om baseline börjar med "Du är ONESEEK..."):
prompt_text: "Du är ONESEEK – en avancerad deltagare med datadriven analys...\n\n[resten av prompten med ändringar applicerade]"

EXEMPEL PÅ FEL:
prompt_text: "BASELINE-PROMPTEN MED SPECIFIKA ÄNDRINGAR"  ❌
prompt_text: "Baseline + ändring om data"  ❌

ALLA TEXTER MÅSTE VARA PÅ SVENSKA!`;
}

/**
 * Generate fallback variants using rule-based modifications
 * @param {string} baselinePrompt - Baseline prompt
 * @param {Object} insights - Insights object
 * @param {number} count - Number of variants
 * @returns {Array} Fallback variants
 */
function generateFallbackVariants(baselinePrompt, insights, count) {
  const variants = [];
  
  const modifications = [
    {
      name: 'data-betoning',
      hypothesis: 'Betona data och bevis ökar trovärdighet',
      modify: (prompt) => prompt + '\n\nPrioritera alltid datadriven analys och citera bevis när det finns tillgängligt.',
      focus: ['data', 'bevis']
    },
    {
      name: 'syntes-fokus',
      hypothesis: 'Starkare syntesmetod förbättrar röstantal',
      modify: (prompt) => prompt.replace('syntetisera', 'djupt syntetisera och integrera').replace('analysera', 'noggrant analysera och jämföra'),
      focus: ['syntes', 'integration']
    },
    {
      name: 'tydlighet-förbättring',
      hypothesis: 'Tydligare struktur och enklare språk förbättrar tillgänglighet',
      modify: (prompt) => prompt + '\n\nAnvänd tydlig struktur med punktlistor. Undvik jargong. Var koncis.',
      focus: ['tydlighet', 'struktur']
    },
    {
      name: 'meta-medvetenhet',
      hypothesis: 'Erkänna olika perspektiv explicit visar djup',
      modify: (prompt) => prompt + '\n\nErkänn och väg explicit olika synvinklar från andra AI:er.',
      focus: ['meta-analys', 'perspektiv']
    },
    {
      name: 'balanserad-metod',
      hypothesis: 'Neutral ton med för/nackdelar ökar förtroende',
      modify: (prompt) => prompt + '\n\nPresent balanserad analys med både fördelar och begränsningar.',
      focus: ['balans', 'neutralitet']
    }
  ];
  
  for (let i = 0; i < Math.min(count, modifications.length); i++) {
    const mod = modifications[i];
    const version = generateVersionNumber(i);
    
    variants.push({
      version: version,
      prompt_text: mod.modify(baselinePrompt),
      hypothesis: mod.hypothesis,
      expected_improvement: `+10-15% förbättring (fallback: ${mod.name})`,
      changes_summary: `Tillämpade ${mod.name} modifiering`,
      strategic_focus: mod.focus,
      metadata: {
        generated_at: new Date().toISOString(),
        generation_method: 'fallback',
        based_on_insights: insights.debates_analyzed
      }
    });
  }
  
  return variants;
}

/**
 * Generate version number for variant
 * @param {number} index - Variant index
 * @returns {string} Version string (e.g., "v1.1.0-a")
 */
function generateVersionNumber(index) {
  const currentDate = new Date();
  const minor = currentDate.getMonth() + 1; // 1-12
  const patch = currentDate.getDate(); // 1-31
  const letter = String.fromCharCode(97 + index); // a, b, c, ...
  
  return `v1.${minor}.${patch}-${letter}`;
}

/**
 * Generate a summary of differences between prompts
 * @param {string} baseline - Baseline prompt
 * @param {string} variant - Variant prompt
 * @returns {string} Diff summary
 */
function generateDiffSummary(baseline, variant) {
  if (!baseline || !variant) {
    return 'Unable to compare';
  }
  
  const baselineWords = baseline.split(/\s+/).length;
  const variantWords = variant.split(/\s+/).length;
  const wordDiff = variantWords - baselineWords;
  
  let summary = `Length: ${wordDiff > 0 ? '+' : ''}${wordDiff} words`;
  
  // Check for major additions
  if (variant.length > baseline.length * 1.2) {
    summary += ', significant additions';
  } else if (variant.length < baseline.length * 0.8) {
    summary += ', significant reductions';
  } else {
    summary += ', similar length';
  }
  
  return summary;
}

/**
 * Validate a prompt variant
 * @param {Object} variant - Prompt variant to validate
 * @returns {Object} Validation result
 */
export function validatePromptVariant(variant) {
  const errors = [];
  const warnings = [];
  
  if (!variant.prompt_text || variant.prompt_text.length < 50) {
    errors.push('Prompt text too short (minimum 50 characters)');
  }
  
  if (variant.prompt_text && variant.prompt_text.length > 5000) {
    warnings.push('Prompt text very long (>5000 characters), may affect performance');
  }
  
  if (!variant.hypothesis) {
    warnings.push('No hypothesis provided');
  }
  
  if (!variant.version) {
    errors.push('Version number missing');
  }
  
  // Check for template placeholders
  if (variant.prompt_text && !variant.prompt_text.includes('{')) {
    warnings.push('No template placeholders found, prompt may not be dynamic');
  }
  
  return {
    valid: errors.length === 0,
    errors,
    warnings
  };
}

export default {
  generatePromptVariants,
  validatePromptVariant,
  generateVersionNumber
};
